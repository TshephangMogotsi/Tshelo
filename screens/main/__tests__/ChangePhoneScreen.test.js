jest.mock('../../../context/ThemeContext', () => ({ useTheme: () => ({ colors: jest.requireActual('../../../theme/themes').lightColors }) }))
jest.mock('../../../context/AuthContext', () => ({ useAuth: () => ({ userId: 'same-account', countryCode: 'BW', refreshProfile: jest.fn().mockResolvedValue(undefined) }) }))
jest.mock('../../../context/ConnectivityContext', () => ({ useRequireOnline: () => () => true }))
jest.mock('../../../lib/changePhone', () => ({ sendCurrentNumberCode: jest.fn(), confirmCurrentNumber: jest.fn(), requestPhoneChange: jest.fn(), confirmPhoneChange: jest.fn(), phoneChangeError: error => error.message }))
jest.mock('../../../lib/api', () => ({ api: { users: { me: jest.fn() } } }))
jest.mock('../../../components/CountryPickerModal', () => 'CountryPicker')
jest.mock('@expo/vector-icons/Ionicons', () => 'Icon')

const React = require('react')
const { act, create } = require('react-test-renderer')
const { Text, TouchableOpacity } = require('react-native')
const Screen = require('../ChangePhoneScreen').default
const { sendCurrentNumberCode, confirmCurrentNumber, requestPhoneChange, confirmPhoneChange } = require('../../../lib/changePhone')
const { api } = require('../../../lib/api')
globalThis.IS_REACT_ACT_ENVIRONMENT = true
let tree
const navigation = { goBack: jest.fn() }
const button = label => tree.root.findAllByType(TouchableOpacity).find(item => item.findAllByType(Text).some(text => text.props.children === label))
const press = label => act(async () => button(label).props.onPress())
const input = (label, value) => act(async () => tree.root.findByProps({ accessibilityLabel: label }).props.onChangeText(value))
beforeEach(async () => {
  jest.clearAllMocks()
  sendCurrentNumberCode.mockResolvedValue('+26771234567')
  confirmCurrentNumber.mockResolvedValue(undefined)
  requestPhoneChange.mockResolvedValue(undefined)
  confirmPhoneChange.mockResolvedValue(undefined)
  api.users.me.mockResolvedValue({ id: 'same-account', phone: '26772345678' })
  await act(async () => { tree = create(React.createElement(Screen, { navigation })) })
})
afterEach(async () => { await act(async () => tree.unmount()) })
async function request() {
  await press('Send code to current number')
  await input('Verification code', '123456')
  await press('Confirm current number')
  await input('New phone number', '72345678')
  await press('Send code to new number')
  await input('Verification code', '123456')
}
it('verifies the new number and confirms the existing profile before success', async () => {
  await request()
  expect(sendCurrentNumberCode).toHaveBeenCalledWith('same-account')
  expect(confirmCurrentNumber).toHaveBeenCalledWith('same-account', '+26771234567', '123456')
  expect(requestPhoneChange).toHaveBeenCalledWith('same-account', '+26772345678')
  await press('Verify and change number')
  expect(confirmPhoneChange).toHaveBeenCalledWith('same-account', '+26772345678', '123456')
  expect(button('Done')).toBeDefined()
})
it('keeps the code step available when verification fails', async () => {
  await request()
  confirmPhoneChange.mockRejectedValue(new Error('Invalid code'))
  await press('Verify and change number')
  expect(button('Done')).toBeUndefined()
  expect(api.users.me).not.toHaveBeenCalled()
  expect(tree.root.findByProps({ accessibilityRole: 'alert' }).props.children).toBe('Invalid code')
})
it('does not allow a new number until the current number code succeeds', async () => {
  await press('Send code to current number')
  await input('Verification code', '123456')
  confirmCurrentNumber.mockRejectedValue(new Error('Incorrect code'))
  await press('Confirm current number')
  expect(tree.root.findByProps({ accessibilityRole: 'alert' }).props.children).toBe('Incorrect code')
  expect(button('Send code to new number')).toBeUndefined()
})
it('retries profile refresh without reusing an already-consumed OTP', async () => {
  await request()
  api.users.me.mockRejectedValueOnce(new Error('Offline'))
  await press('Verify and change number')
  expect(button('Refresh account')).toBeDefined()
  await press('Refresh account')
  expect(confirmPhoneChange).toHaveBeenCalledTimes(1)
  expect(button('Done')).toBeDefined()
})
it('does not claim success if the hosted profile-sync migration is missing', async () => {
  await request()
  api.users.me.mockResolvedValue({ id: 'same-account', phone: '26771234567' })
  await press('Verify and change number')
  expect(button('Done')).toBeUndefined()
  expect(button('Refresh account')).toBeDefined()
})
