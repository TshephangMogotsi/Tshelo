test('independent health check fails closed for stale, missing, failed or disabled monitoring', () => {
  const healthy={fresh:true,monitor_scheduled:true,issues:[],open_incidents:0,latest_monitor_run_status:'succeeded'}
  assert.equal(waitlistHealthPasses(healthy),true)
  for (const health of [null,{}, {...healthy,fresh:false}, {...healthy,monitor_scheduled:false},
    {...healthy,issues:['run_failed']}, {...healthy,open_incidents:1},
    {...healthy,latest_monitor_run_status:'failed'}, {...healthy,latest_monitor_run_status:null}]) {
    assert.equal(waitlistHealthPasses(health),false)
  }
})

test('waitlist cleanup monitor detects failure, missed jobs, drift and recovery without client exposure', async () => {
  const db = new PGlite()
  try {
    // pg_cron is unavailable in PGlite. Model its job/history catalog, then run
    // the actual monitor migration and the same SQL regression used live/CI.
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA cron;
      CREATE TABLE cron.job(jobid bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,jobname text UNIQUE,schedule text,command text,username text,database text,active boolean);
      CREATE TABLE cron.job_run_details(jobid bigint,runid bigint PRIMARY KEY,status text,start_time timestamptz,end_time timestamptz,return_message text);
      CREATE FUNCTION cron.schedule(text,text,text) RETURNS bigint LANGUAGE sql AS 'INSERT INTO cron.job(jobname,schedule,command,username,database,active) VALUES($1,$2,$3,''postgres'',current_database(),true) ON CONFLICT(jobname) DO UPDATE SET schedule=excluded.schedule,command=excluded.command RETURNING jobid';
      CREATE FUNCTION cron.alter_job(job_id bigint,schedule text DEFAULT NULL,command text DEFAULT NULL,database text DEFAULT NULL,username text DEFAULT NULL,active boolean DEFAULT NULL) RETURNS void LANGUAGE sql AS 'UPDATE cron.job j SET schedule=coalesce($2,j.schedule),active=coalesce($6,j.active) WHERE jobid=$1';
      CREATE FUNCTION cron.unschedule(bigint) RETURNS boolean LANGUAGE sql AS 'DELETE FROM cron.job WHERE jobid=$1 RETURNING true';
      CREATE FUNCTION public.assert_application_table_security() RETURNS void LANGUAGE sql AS 'SELECT';
      SELECT set_config('cron.log_run','on',false);
      INSERT INTO cron.job VALUES(1,'tshelo-country-waitlist-cleanup','15 2 * * *',
        'SELECT public.purge_expired_country_waitlist();','postgres',current_database(),true);
      INSERT INTO cron.job_run_details VALUES(1,1,'succeeded',now(),now(),NULL);`)
    await db.exec(await readFile(new URL('../../supabase/migrations/20261016120000_monitor_waitlist_cleanup.sql',import.meta.url),'utf8'))
    const result = (await db.exec(await readFile(new URL('../../supabase/tests/waitlist_cleanup_monitor.sql',import.meta.url),'utf8'))).at(-1).rows[0].evidence
    assert.equal(result.result,'PASS')
    assert.equal(result.fixtures_rolled_back,true)
    assert.equal(result.checks.length,13)
    assert.equal((await db.query('SELECT count(*)::int AS n FROM waitlist_cleanup_incidents')).rows[0].n,0)
    assert.equal((await db.query('SELECT count(*)::int AS n FROM cron.job_run_details WHERE runid<0')).rows[0].n,0)
    // cron.log_run is restart-only in hosted pg_cron. Exercise the disabled
    // branch here without changing/restarting production configuration.
    await db.exec("SELECT set_config('cron.log_run','off',false); SELECT public.monitor_country_waitlist_cleanup()")
    assert.ok((await db.query('SELECT issues FROM waitlist_cleanup_health')).rows[0].issues.includes('cron_history_disabled'))
  } finally { await db.close() }
})
